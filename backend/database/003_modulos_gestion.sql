BEGIN;

ALTER TABLE servicios
  ADD COLUMN IF NOT EXISTS codigo VARCHAR(32),
  ADD COLUMN IF NOT EXISTS descripcion TEXT,
  ADD COLUMN IF NOT EXISTS unidad VARCHAR(40) NOT NULL DEFAULT 'Servicio',
  ADD COLUMN IF NOT EXISTS precio_numerico NUMERIC(14, 2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS moneda VARCHAR(20) NOT NULL DEFAULT 'COP',
  ADD COLUMN IF NOT EXISTS categoria VARCHAR(80) NOT NULL DEFAULT 'Instalación',
  ADD COLUMN IF NOT EXISTS estado VARCHAR(20) NOT NULL DEFAULT 'Activo',
  ADD COLUMN IF NOT EXISTS horas NUMERIC(8, 2) NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now();

UPDATE servicios
SET codigo = 'ELEC-' || lpad(id::text, 3, '0')
WHERE codigo IS NULL OR btrim(codigo) = '';

UPDATE servicios
SET horas = CASE
  WHEN upper(moneda) = 'USD / H' THEN 4
  WHEN upper(moneda) IN ('USD', 'COP', 'COP / H') THEN 8
  ELSE 1
END;

CREATE UNIQUE INDEX IF NOT EXISTS ux_servicios_codigo
  ON servicios (codigo);

ALTER TABLE usuarios
  ADD COLUMN IF NOT EXISTS telefono VARCHAR(30),
  ADD COLUMN IF NOT EXISTS zona VARCHAR(80) NOT NULL DEFAULT 'General';

ALTER TABLE roles
  ADD COLUMN IF NOT EXISTS codigo VARCHAR(40),
  ADD COLUMN IF NOT EXISTS descripcion TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS plataformas TEXT[] NOT NULL DEFAULT ARRAY['Web']::TEXT[],
  ADD COLUMN IF NOT EXISTS estado VARCHAR(20) NOT NULL DEFAULT 'Activo',
  ADD COLUMN IF NOT EXISTS permisos JSONB NOT NULL DEFAULT '{}'::JSONB;

UPDATE roles
SET codigo = 'ROL-' || upper(regexp_replace(nombre, '[^A-Za-z0-9]+', '-', 'g'))
WHERE codigo IS NULL OR btrim(codigo) = '';

CREATE TABLE IF NOT EXISTS categorias_materiales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  unidad VARCHAR(40) NOT NULL DEFAULT 'Unidad',
  prefijo VARCHAR(12) NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_categorias_materiales_nombre
  ON categorias_materiales (lower(nombre));

INSERT INTO categorias_materiales (nombre, unidad, prefijo)
SELECT datos.nombre, datos.unidad, datos.prefijo
FROM (VALUES
  ('Conductores', 'Metro', 'EL-BUS'),
  ('Aparamenta', 'Unidad', 'EL-APA'),
  ('Cables', 'Metro', 'EL-CAB'),
  ('Canalización', 'Metro', 'EL-CAN'),
  ('Transformadores', 'Unidad', 'EL-TRF'),
  ('Accesorios', 'Pieza', 'EL-ACC'),
  ('Iluminación', 'Unidad', 'EL-ILU'),
  ('Herramientas', 'Unidad', 'EL-HER')
) AS datos(nombre, unidad, prefijo)
WHERE NOT EXISTS (
  SELECT 1 FROM categorias_materiales existente
  WHERE lower(existente.nombre) = lower(datos.nombre)
);

CREATE TABLE IF NOT EXISTS materiales (
  codigo VARCHAR(32) PRIMARY KEY,
  nombre VARCHAR(180) NOT NULL,
  categoria_id BIGINT NOT NULL REFERENCES categorias_materiales(id) ON UPDATE CASCADE,
  stock NUMERIC(14, 3) NOT NULL DEFAULT 0 CHECK (stock >= 0),
  unidad VARCHAR(40) NOT NULL DEFAULT 'Unidad',
  precio_unitario NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (precio_unitario >= 0),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_materiales_categoria
  ON materiales (categoria_id);

CREATE TABLE IF NOT EXISTS cotizaciones (
  codigo VARCHAR(32) PRIMARY KEY,
  cliente_id INT REFERENCES clientes(id) ON DELETE SET NULL,
  cliente_nombre VARCHAR(180) NOT NULL,
  documento VARCHAR(50) NOT NULL DEFAULT '',
  contacto VARCHAR(150) NOT NULL DEFAULT '',
  telefono VARCHAR(40) NOT NULL DEFAULT '',
  correo VARCHAR(150) NOT NULL DEFAULT '',
  direccion TEXT NOT NULL DEFAULT '',
  proyecto VARCHAR(180) NOT NULL,
  fecha_emision DATE NOT NULL DEFAULT CURRENT_DATE,
  dias_vigencia INT NOT NULL DEFAULT 30 CHECK (dias_vigencia > 0),
  iva_porcentaje NUMERIC(5, 2) NOT NULL DEFAULT 16 CHECK (iva_porcentaje BETWEEN 0 AND 100),
  descuento NUMERIC(5, 2) NOT NULL DEFAULT 0 CHECK (descuento BETWEEN 0 AND 100),
  estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente'
    CHECK (estado IN ('Aprobado', 'Pendiente', 'Rechazado')),
  notas TEXT NOT NULL DEFAULT '',
  subtotal NUMERIC(14, 2) NOT NULL DEFAULT 0,
  monto_descuento NUMERIC(14, 2) NOT NULL DEFAULT 0,
  monto_impuesto NUMERIC(14, 2) NOT NULL DEFAULT 0,
  total NUMERIC(14, 2) NOT NULL DEFAULT 0,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_cotizaciones_cliente
  ON cotizaciones (cliente_id);

CREATE TABLE IF NOT EXISTS cotizacion_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cotizacion_codigo VARCHAR(32) NOT NULL
    REFERENCES cotizaciones(codigo) ON DELETE CASCADE,
  tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('servicio', 'material', 'item')),
  referencia_id TEXT,
  descripcion VARCHAR(240) NOT NULL,
  cantidad NUMERIC(14, 3) NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(14, 2) NOT NULL CHECK (precio_unitario >= 0),
  unidad VARCHAR(40) NOT NULL DEFAULT 'Unidad',
  moneda_servicio VARCHAR(20),
  orden INT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_cotizacion_items_codigo
  ON cotizacion_items (cotizacion_codigo, orden, id);

CREATE TABLE IF NOT EXISTS pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(32) UNIQUE,
  cotizacion_codigo VARCHAR(32)
    REFERENCES cotizaciones(codigo) ON DELETE SET NULL,
  cotizacion_referencia VARCHAR(32) NOT NULL,
  cliente_nombre VARCHAR(180) NOT NULL DEFAULT '',
  documento VARCHAR(50) NOT NULL DEFAULT '',
  proyecto VARCHAR(180) NOT NULL DEFAULT '',
  monto_total NUMERIC(14, 2) NOT NULL DEFAULT 0,
  monto NUMERIC(14, 2) NOT NULL CHECK (monto > 0),
  fecha DATE NOT NULL DEFAULT CURRENT_DATE,
  hora TIME NOT NULL DEFAULT '09:00',
  metodo VARCHAR(40) NOT NULL,
  referencia VARCHAR(120) NOT NULL DEFAULT '',
  nota TEXT NOT NULL DEFAULT '',
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_pagos_cotizacion
  ON pagos (cotizacion_codigo);

CREATE TABLE IF NOT EXISTS agenda_actividades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(32) UNIQUE NOT NULL,
  cliente_id INT NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
  servicio_id INT NOT NULL REFERENCES servicios(id) ON DELETE RESTRICT,
  tercero_id INT NOT NULL REFERENCES terceros(id) ON DELETE RESTRICT,
  fecha DATE NOT NULL,
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  horas NUMERIC(8, 2) NOT NULL CHECK (horas > 0),
  estado VARCHAR(24) NOT NULL DEFAULT 'Programada'
    CHECK (estado IN ('Programada', 'En proceso', 'Completada', 'Cancelada')),
  prioridad VARCHAR(16) NOT NULL DEFAULT 'Media'
    CHECK (prioridad IN ('Baja', 'Media', 'Alta')),
  descripcion TEXT NOT NULL DEFAULT '',
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (hora_fin > hora_inicio)
);

CREATE INDEX IF NOT EXISTS idx_agenda_fecha_tecnico
  ON agenda_actividades (fecha, tercero_id, hora_inicio);

COMMIT;
