BEGIN;

-- Ajustes solicitados para la gestión de servicios, materiales, terceros y cotizaciones.
-- Todo el contenido es aditivo: no elimina columnas, datos ni objetos existentes.

-- 1) Categorías de servicios administrables desde la interfaz -------------------
CREATE TABLE IF NOT EXISTS categorias_servicio (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  estado VARCHAR(20) NOT NULL DEFAULT 'Activo'
    CHECK (estado IN ('Activo', 'Inactivo'))
);

ALTER TABLE categorias_servicio
  ADD COLUMN IF NOT EXISTS estado VARCHAR(20) NOT NULL DEFAULT 'Activo';

CREATE UNIQUE INDEX IF NOT EXISTS ux_categorias_servicio_nombre
  ON categorias_servicio (lower(nombre));

ALTER TABLE servicios
  ADD COLUMN IF NOT EXISTS categoria_id INT REFERENCES categorias_servicio(id)
    ON DELETE SET NULL ON UPDATE CASCADE;

CREATE INDEX IF NOT EXISTS idx_servicios_categoria_id
  ON servicios (categoria_id);

-- Deja registradas las categorías que ya venían escritas en cada servicio.
INSERT INTO categorias_servicio (nombre)
SELECT DISTINCT trim(s.categoria)
FROM servicios s
WHERE s.categoria IS NOT NULL
  AND btrim(s.categoria) <> ''
  AND NOT EXISTS (
    SELECT 1 FROM categorias_servicio c
    WHERE lower(c.nombre) = lower(btrim(s.categoria))
  );

-- Vincula el texto de categoría con su registro administrativo.
UPDATE servicios s
SET categoria_id = c.id
FROM categorias_servicio c
WHERE lower(c.nombre) = lower(btrim(s.categoria))
  AND s.categoria_id IS NULL;

-- 2) Estado y stock mínimo de los materiales -----------------------------------
ALTER TABLE materiales
  ADD COLUMN IF NOT EXISTS estado VARCHAR(20) NOT NULL DEFAULT 'Activo'
    CHECK (estado IN ('Activo', 'Inactivo')),
  ADD COLUMN IF NOT EXISTS stock_minimo NUMERIC(14, 3) NOT NULL DEFAULT 10
    CHECK (stock_minimo >= 0);

-- 3) Materiales vinculados a un servicio (despliegue automático en cotización) --
CREATE TABLE IF NOT EXISTS servicios_materiales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  servicio_id INT NOT NULL REFERENCES servicios(id) ON DELETE CASCADE,
  material_codigo VARCHAR(32) NOT NULL REFERENCES materiales(codigo)
    ON UPDATE CASCADE,
  cantidad NUMERIC(14, 3) NOT NULL DEFAULT 1 CHECK (cantidad > 0),
  obligatorio BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (servicio_id, material_codigo)
);

CREATE INDEX IF NOT EXISTS idx_servicios_materiales_servicio
  ON servicios_materiales (servicio_id);

-- 4) Un mismo material no puede repetirse dentro de la misma cotización ---------
-- El índice es aditivo y condicional: si el historial ya trae materiales repetidos
-- en una misma cotización se avisa y se omite, sin borrar ni modificar filas existentes.
DO $bloque$
BEGIN
  IF to_regclass('public.ux_cotizacion_items_material') IS NOT NULL THEN
    RAISE NOTICE 'El índice ux_cotizacion_items_material ya existe, se omite.';
    RETURN;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM cotizacion_items
    WHERE tipo = 'material'
    GROUP BY cotizacion_codigo, referencia_id
    HAVING COUNT(*) > 1
  ) THEN
    RAISE NOTICE 'Ya hay materiales repetidos en cotizaciones históricas; se omite el índice único para no borrar datos.';
    RETURN;
  END IF;

  EXECUTE $crear$
    CREATE UNIQUE INDEX ux_cotizacion_items_material
      ON cotizacion_items (cotizacion_codigo, referencia_id)
      WHERE tipo = 'material'
  $crear$;
END
$bloque$;

-- 5) Términos, condiciones y garantías de la cotización -------------------------
ALTER TABLE cotizaciones
  ADD COLUMN IF NOT EXISTS terminos TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS garantias TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS stock_descontado BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS aprobado_en TIMESTAMPTZ;

-- 6) Tipo de documento y relación empleado <-> cliente --------------------------
ALTER TABLE clientes
  ADD COLUMN IF NOT EXISTS tipo_documento VARCHAR(30) NOT NULL DEFAULT 'NIT',
  ADD COLUMN IF NOT EXISTS tercero_id INT REFERENCES terceros(id)
    ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS es_empleado BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS idx_clientes_tercero
  ON clientes (tercero_id);

-- 7) Datos de residencia del tercero (técnico/colaborador) ----------------------
ALTER TABLE terceros
  ADD COLUMN IF NOT EXISTS tipo_documento VARCHAR(30) NOT NULL DEFAULT 'Cédula',
  ADD COLUMN IF NOT EXISTS direccion TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS municipio VARCHAR(80) NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS departamento VARCHAR(80) NOT NULL DEFAULT '';

COMMIT;
