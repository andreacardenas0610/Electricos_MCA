  WHERE usado_en IS NULL;

CREATE TABLE IF NOT EXISTS tipos_propiedad (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS clientes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id BIGINT REFERENCES personas(id) ON UPDATE CASCADE ON DELETE SET NULL,
  nombre_razon_social VARCHAR(180) NOT NULL,
  documento_nit VARCHAR(50) NOT NULL UNIQUE,
  tipo_cliente VARCHAR(20) NOT NULL DEFAULT 'Natural'
    CHECK (tipo_cliente IN ('Natural', 'Jurídico')),
  tipo_documento VARCHAR(30) NOT NULL DEFAULT 'Cédula',
  tipo_propiedad_id INT REFERENCES tipos_propiedad(id) ON UPDATE CASCADE ON DELETE SET NULL,
  tercero_id INT REFERENCES terceros(id) ON UPDATE CASCADE ON DELETE SET NULL,
  es_empleado BOOLEAN NOT NULL DEFAULT FALSE,
  estado VARCHAR(20) NOT NULL DEFAULT 'Activo'
    CHECK (estado IN ('Activo', 'Inactivo')),
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS contactos_cliente (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id INT NOT NULL REFERENCES clientes(id) ON UPDATE CASCADE ON DELETE CASCADE,
