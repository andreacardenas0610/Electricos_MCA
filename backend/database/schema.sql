BEGIN;

CREATE TABLE IF NOT EXISTS personas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_documento VARCHAR(30) NOT NULL DEFAULT 'Cédula',
  documento VARCHAR(50) NOT NULL,
  nombre_completo VARCHAR(180) NOT NULL,
  telefono VARCHAR(30),
  correo_electronico VARCHAR(150),
  estado VARCHAR(20) NOT NULL DEFAULT 'Activo'
    CHECK (estado IN ('Activo', 'Inactivo')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_personas_documento
  ON personas (upper(btrim(documento)));

CREATE INDEX IF NOT EXISTS idx_personas_correo
  ON personas (lower(btrim(correo_electronico)))
  WHERE correo_electronico IS NOT NULL;

CREATE TABLE IF NOT EXISTS roles (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  codigo VARCHAR(40) NOT NULL UNIQUE,
  descripcion TEXT NOT NULL DEFAULT '',
  plataformas TEXT[] NOT NULL DEFAULT ARRAY['Web']::TEXT[],
  estado VARCHAR(20) NOT NULL DEFAULT 'Activo'
    CHECK (estado IN ('Activo', 'Inactivo')),
  permisos JSONB NOT NULL DEFAULT '{}'::JSONB,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS terceros (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id BIGINT UNIQUE REFERENCES personas(id) ON UPDATE CASCADE ON DELETE SET NULL,
  nombre_completo VARCHAR(150) NOT NULL,
  tipo_documento VARCHAR(30) NOT NULL DEFAULT 'Cédula',
  documento VARCHAR(30) NOT NULL UNIQUE,
  empresa VARCHAR(150),
  telefono VARCHAR(30),
  correo_electronico VARCHAR(150),
  direccion TEXT NOT NULL DEFAULT '',
  municipio VARCHAR(80) NOT NULL DEFAULT '',
  departamento VARCHAR(80) NOT NULL DEFAULT '',
  estado VARCHAR(20) NOT NULL DEFAULT 'Activo'
    CHECK (estado IN ('Activo', 'Inactivo')),
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_terceros_correo
  ON terceros (lower(correo_electronico))
  WHERE correo_electronico IS NOT NULL;

CREATE TABLE IF NOT EXISTS usuarios (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id BIGINT UNIQUE REFERENCES personas(id) ON UPDATE CASCADE ON DELETE SET NULL,
  nombre_completo VARCHAR(150) NOT NULL,
  usuario VARCHAR(50) NOT NULL,
  correo_electronico VARCHAR(150),
  password_hash VARCHAR(255) NOT NULL,
  telefono VARCHAR(30),
  zona VARCHAR(80) NOT NULL DEFAULT 'General',
  estado VARCHAR(20) NOT NULL DEFAULT 'Activo'
    CHECK (estado IN ('Activo', 'Inactivo')),
  verificado BOOLEAN NOT NULL DEFAULT FALSE,
  rol_id INT NOT NULL REFERENCES roles(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  tercero_id INT UNIQUE REFERENCES terceros(id) ON UPDATE CASCADE ON DELETE SET NULL,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_usuarios_usuario
  ON usuarios (lower(usuario));

CREATE UNIQUE INDEX IF NOT EXISTS ux_usuarios_correo
  ON usuarios (lower(correo_electronico));

CREATE TABLE IF NOT EXISTS tokens_verificacion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL REFERENCES usuarios(id) ON UPDATE CASCADE ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  proposito VARCHAR(24) NOT NULL
    CHECK (proposito IN ('verificacion', 'recuperacion')),
  expira_en TIMESTAMPTZ NOT NULL,
  usado_en TIMESTAMPTZ,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
