BEGIN;

CREATE TABLE IF NOT EXISTS personas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_documento VARCHAR(30) NOT NULL DEFAULT 'Cédula',
  documento VARCHAR(50) NOT NULL,
  nombre_completo VARCHAR(180) NOT NULL,
  telefono VARCHAR(40),
  correo_electronico VARCHAR(150),
  estado VARCHAR(20) NOT NULL DEFAULT 'Activo'
    CHECK (estado IN ('Activo', 'Inactivo')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_personas_documento
  ON personas (upper(btrim(documento)));

DROP INDEX IF EXISTS ux_personas_correo;

CREATE INDEX IF NOT EXISTS idx_personas_correo
  ON personas (lower(btrim(correo_electronico)))
  WHERE correo_electronico IS NOT NULL;

ALTER TABLE terceros ADD COLUMN IF NOT EXISTS persona_id BIGINT;
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS persona_id BIGINT;
ALTER TABLE clientes ADD COLUMN IF NOT EXISTS persona_id BIGINT;

DO $migra_personas$
DECLARE
  registro RECORD;
  v_persona_id BIGINT;
BEGIN
  FOR registro IN
    SELECT id, nombre_completo, tipo_documento, documento,
           telefono, correo_electronico, estado
    FROM terceros
  LOOP
    SELECT p.id INTO v_persona_id
    FROM personas p
    WHERE upper(btrim(p.documento)) = upper(btrim(registro.documento))
    LIMIT 1;

    IF v_persona_id IS NULL THEN
      INSERT INTO personas
        (tipo_documento, documento, nombre_completo, telefono, correo_electronico, estado)
      VALUES
        (COALESCE(registro.tipo_documento, 'Cédula'),
         registro.documento, registro.nombre_completo,
         registro.telefono, lower(NULLIF(btrim(registro.correo_electronico), '')),
         COALESCE(registro.estado, 'Activo'))
      RETURNING id INTO v_persona_id;
    ELSE
      UPDATE personas
      SET nombre_completo = registro.nombre_completo,
          tipo_documento = COALESCE(registro.tipo_documento, tipo_documento),
          telefono = COALESCE(registro.telefono, telefono),
          correo_electronico = COALESCE(lower(NULLIF(btrim(registro.correo_electronico), '')), correo_electronico),
          estado = COALESCE(registro.estado, estado),
          actualizado_en = now()
      WHERE id = v_persona_id;
    END IF;

    UPDATE terceros SET persona_id = v_persona_id WHERE id = registro.id;
  END LOOP;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'usuarios' AND column_name = 'documento_n'
  ) THEN
    FOR registro IN
      SELECT u.id, u.nombre_completo, u.documento_n AS documento,
             u.telefono, u.correo_electronico, u.estado,
             COALESCE(t.tipo_documento, 'Cédula') AS tipo_documento
      FROM usuarios u
      LEFT JOIN terceros t ON t.id = u.tercero_id
    LOOP
      SELECT p.id INTO v_persona_id
      FROM personas p
      WHERE upper(btrim(p.documento)) = upper(btrim(registro.documento))
      LIMIT 1;

      IF v_persona_id IS NULL THEN
        INSERT INTO personas
          (tipo_documento, documento, nombre_completo, telefono, correo_electronico, estado)
        VALUES
          (registro.tipo_documento, registro.documento, registro.nombre_completo,
           registro.telefono, lower(NULLIF(btrim(registro.correo_electronico), '')),
           COALESCE(registro.estado, 'Activo'))
        RETURNING id INTO v_persona_id;
      END IF;

      UPDATE usuarios SET persona_id = v_persona_id WHERE id = registro.id;
      UPDATE terceros
      SET persona_id = v_persona_id
      WHERE id = (SELECT tercero_id FROM usuarios WHERE id = registro.id);
    END LOOP;
  END IF;

  FOR registro IN
    SELECT c.id, c.nombre_razon_social AS nombre_completo,
           c.tipo_documento, c.documento_nit AS documento,
           cc.telefono, cc.correo_electronico, c.estado
    FROM clientes c
    LEFT JOIN contactos_cliente cc
      ON cc.cliente_id = c.id AND cc.es_principal = TRUE
  LOOP
    SELECT p.id INTO v_persona_id
    FROM personas p
    WHERE upper(btrim(p.documento)) = upper(btrim(registro.documento))
    LIMIT 1;

    IF v_persona_id IS NULL THEN
      INSERT INTO personas
        (tipo_documento, documento, nombre_completo, telefono, correo_electronico, estado)
      VALUES
        (COALESCE(registro.tipo_documento, 'Cédula'), registro.documento,
         registro.nombre_completo, registro.telefono,
         lower(NULLIF(btrim(registro.correo_electronico), '')),
         COALESCE(registro.estado, 'Activo'))
      RETURNING id INTO v_persona_id;
    END IF;

    UPDATE clientes SET persona_id = v_persona_id WHERE id = registro.id;
  END LOOP;
END
$migra_personas$;

DO $constraints$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'fk_terceros_persona'
  ) THEN
    ALTER TABLE terceros
      ADD CONSTRAINT fk_terceros_persona
      FOREIGN KEY (persona_id) REFERENCES personas(id)
      ON UPDATE CASCADE ON DELETE SET NULL;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuarios_persona'
  ) THEN
    ALTER TABLE usuarios
      ADD CONSTRAINT fk_usuarios_persona
      FOREIGN KEY (persona_id) REFERENCES personas(id)
      ON UPDATE CASCADE ON DELETE SET NULL;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'fk_clientes_persona'
  ) THEN
    ALTER TABLE clientes
      ADD CONSTRAINT fk_clientes_persona
      FOREIGN KEY (persona_id) REFERENCES personas(id)
      ON UPDATE CASCADE ON DELETE SET NULL;
  END IF;
END
$constraints$;

CREATE UNIQUE INDEX IF NOT EXISTS ux_terceros_persona
  ON terceros (persona_id) WHERE persona_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_usuarios_persona
  ON usuarios (persona_id) WHERE persona_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_clientes_persona
  ON clientes (persona_id);

COMMIT;
