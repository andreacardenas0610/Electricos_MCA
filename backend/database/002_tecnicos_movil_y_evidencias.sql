BEGIN;

CREATE TABLE IF NOT EXISTS terceros (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_completo VARCHAR(150),
  documento VARCHAR(30),
  empresa VARCHAR(150),
  telefono VARCHAR(20),
  correo_electronico VARCHAR(100),
  usuario VARCHAR(50),
  password_hash VARCHAR(255),
  estado VARCHAR(20) NOT NULL DEFAULT 'Activo'
    CHECK (estado IN ('Activo', 'Inactivo')),
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE terceros
  ADD COLUMN IF NOT EXISTS nombre_completo VARCHAR(150),
  ADD COLUMN IF NOT EXISTS documento VARCHAR(30),
  ADD COLUMN IF NOT EXISTS empresa VARCHAR(150),
  ADD COLUMN IF NOT EXISTS telefono VARCHAR(20),
  ADD COLUMN IF NOT EXISTS correo_electronico VARCHAR(100),
  ADD COLUMN IF NOT EXISTS usuario VARCHAR(50),
  ADD COLUMN IF NOT EXISTS password_hash VARCHAR(255),
  ADD COLUMN IF NOT EXISTS fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now();

CREATE UNIQUE INDEX IF NOT EXISTS ux_terceros_usuario
  ON terceros (lower(usuario))
  WHERE usuario IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_terceros_documento
  ON terceros (documento)
  WHERE documento IS NOT NULL;

ALTER TABLE ordenes_servicio
  ADD COLUMN IF NOT EXISTS servicio_id INT,
  ADD COLUMN IF NOT EXISTS tercero_id INT,
  ADD COLUMN IF NOT EXISTS fecha_programada DATE,
  ALTER COLUMN tecnico_usuario_id DROP NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_os_servicio') THEN
    ALTER TABLE ordenes_servicio
      ADD CONSTRAINT fk_os_servicio
      FOREIGN KEY (servicio_id) REFERENCES servicios(id);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_os_tercero') THEN
    ALTER TABLE ordenes_servicio
      ADD CONSTRAINT fk_os_tercero
      FOREIGN KEY (tercero_id) REFERENCES terceros(id);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_ordenes_tercero
  ON ordenes_servicio (tercero_id);

ALTER TABLE evidencias_orden
  ALTER COLUMN usuario_id DROP NOT NULL,
  ALTER COLUMN url_archivo DROP NOT NULL,
  ADD COLUMN IF NOT EXISTS tercero_id INT,
  ADD COLUMN IF NOT EXISTS nombre_archivo VARCHAR(255),
  ADD COLUMN IF NOT EXISTS mime_type VARCHAR(100),
  ADD COLUMN IF NOT EXISTS contenido BYTEA;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_evid_tercero') THEN
    ALTER TABLE evidencias_orden
      ADD CONSTRAINT fk_evid_tercero
      FOREIGN KEY (tercero_id) REFERENCES terceros(id);
  END IF;
END $$;

ALTER TABLE seguimiento_orden
  ALTER COLUMN usuario_id DROP NOT NULL,
  ADD COLUMN IF NOT EXISTS tercero_id INT;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_seg_tercero') THEN
    ALTER TABLE seguimiento_orden
      ADD CONSTRAINT fk_seg_tercero
      FOREIGN KEY (tercero_id) REFERENCES terceros(id);
  END IF;
END $$;

COMMIT;
